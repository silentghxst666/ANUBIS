function table(head, rows, widths) {
  const x0 = doc.page.margins.left;
  let y = doc.y + 4;
  const rowH = (cells, font) =>
    Math.max(...cells.map((c, i) => doc.font(font).fontSize(8.5).heightOfString(String(c), { width: widths[i] - 8 }))) + 8;
  const draw = (cells, font, fill) => {
    const h = rowH(cells, font);
    if (y + h > doc.page.height - 50) {
      doc.addPage();
      y = doc.y;
    }
    if (fill) doc.rect(x0, y, widths.reduce((a, b) => a + b), h).fill(fill);
    let x = x0;
    cells.forEach((c, i) => {
      doc.font(font).fontSize(8.5).fillColor("#000").text(String(c), x + 4, y + 4, { width: widths[i] - 8 });
      x += widths[i];
    });
    doc.moveTo(x0, y + h).lineTo(x0 + widths.reduce((a, b) => a + b), y + h).lineWidth(0.4).strokeColor("#bbb").stroke();
    y += h;
  };
  draw(head, "B", "#eee");
  rows.forEach((r) => draw(r, "R"));
  doc.x = x0;
  doc.y = y + 6;
}

